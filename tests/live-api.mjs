// Parent supplies synthetic credentials only through stdin, never argv or files.
import assert from 'node:assert/strict';
import readline from 'node:readline';
import {createAuth} from '../frontend/js/services/auth.js';
import {createRepository} from '../frontend/js/data/repository.js';
const input=readline.createInterface({input:process.stdin});const lines=input[Symbol.asyncIterator]();
const data=JSON.parse((await lines.next()).value);
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
console.log(JSON.stringify({phase:'signing_in'}));
const auth=createAuth(data.config,storage);await auth.signIn(data.email,data.password);
console.log(JSON.stringify({phase:'signed_in'}));
const api=createRepository(auth,(url,opts)=>fetch(data.origin+url,opts),data.config.apiBase);
const me=await api.me();assert.ok(me.id);assert.equal((await api.listDreams()).length,0);
const original='  I walked across a wooden bridge in a quiet forest.\nI heard birds and felt calm.  ';
const draft=await api.saveDream({title:'Frontend integration fixture',dream_date:'2026-10-30',text:original,reported_emotions:['calm'],lifecycle:'draft'});
assert.equal(draft.text,original);assert.equal(draft.analysis_state,'not_requested');
const saved=await api.updateDream(draft.id,{expected_version:draft.version,lifecycle:'saved'});
assert.equal(saved.text,original);assert.ok(saved.analysis_job_id);
assert.equal((await api.listDreams({keyword:'wooden bridge'}))[0].id,saved.id);
assert.ok((await api.job(saved.analysis_job_id)).status);
console.log(JSON.stringify({drain:true,phase:'journal_saved'}));await lines.next();
const analysis=await api.analysis(saved.id);assert.equal(analysis.status,'ready');assert.ok(analysis.evidence.length);
assert.ok((await api.constellation()).nodes.length);assert.ok((await api.motifs()).length);
assert.equal((await api.insights('2026-10','Asia/Karachi')).dream_date_count,1);
const conversation=await api.createConversation('Frontend verification');
await api.ask(conversation.id,'What did I hear in the forest?',[saved.id]);
const exp=await api.exportJournal('json');
console.log(JSON.stringify({drain:true,phase:'analysis_verified_chat_export_queued'}));await lines.next();
const messages=await api.messages(conversation.id);assert.ok(messages.items.some(x=>x.role==='assistant' && x.status==='completed'));
const ready=await api.exportStatus(exp.id);assert.ok(ready.download_url);
const blob=await api.download(ready.download_url);const exported=JSON.parse(await blob.text());assert.equal(exported.dreams[0].text ?? exported.dreams[0].original_text ?? exported.dreams[0].revisions?.[0]?.text,original);
const profile=await api.updateMe({expected_version:me.version,display_name:'Synthetic frontend check',timezone:'Asia/Karachi'});assert.equal(profile.timezone,'Asia/Karachi');
let p=await api.preferences();p=await api.updatePreferences({expected_version:p.version,reduced_motion:true});assert.equal(p.reduced_motion,true);
const memory=await api.saveMemory({motif:{type:'object',label:'Synthetic bridge'},meaning:'A test crossing'});
await api.updateMemory(memory.id,{expected_version:memory.version,meaning:'A deliberate test meaning'});
const memories=await api.memory();const updated=memories.find(x=>x.id===memory.id);await api.deleteMemory(memory.id,updated.version);
await api.deleteConversation(conversation.id);await api.deleteDream(saved.id);assert.equal((await api.listDreams()).length,0);
await auth.signOut();assert.equal(await auth.token(),null);
console.log(JSON.stringify({complete:true,checks:['real_auth','proxy','journal','exact_source','worker_analysis','evidence','graph','motifs','insights','detective','export','profile','preferences','memory','deletion','logout']}));input.close();
